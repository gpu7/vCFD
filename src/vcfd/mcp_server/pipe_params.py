"""Update Hagen–Poiseuille pipe case parameters in OpenFOAM dictionaries."""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any

from vcfd.mcp_server.cases import read_meta, write_meta


def set_pipe_parameters(
    case_dir: Path,
    *,
    radius: float | None = None,
    length: float | None = None,
    viscosity: float | None = None,
    density: float | None = None,
    bulk_velocity: float | None = None,
    n_axial: int | None = None,
    n_radial: int | None = None,
) -> dict[str, Any]:
    """Write physical and mesh parameters into case files + vcfd.json."""
    meta = read_meta(case_dir)
    params: dict[str, Any] = dict(meta.get("parameters") or {})

    # Defaults chosen for clearly laminar Re ≈ 100 (ρ U D / μ).
    defaults = {
        "radius": 0.05,
        "length": 1.0,
        "viscosity": 0.1,
        "density": 1000.0,
        "bulk_velocity": 0.1,
        "n_axial": 40,
        "n_radial": 10,
    }
    for k, v in defaults.items():
        params.setdefault(k, v)

    if radius is not None:
        params["radius"] = float(radius)
    if length is not None:
        params["length"] = float(length)
    if viscosity is not None:
        params["viscosity"] = float(viscosity)
    if density is not None:
        params["density"] = float(density)
    if bulk_velocity is not None:
        params["bulk_velocity"] = float(bulk_velocity)
    if n_axial is not None:
        params["n_axial"] = int(n_axial)
    if n_radial is not None:
        params["n_radial"] = int(n_radial)

    r = float(params["radius"])
    L = float(params["length"])
    nu = float(params["viscosity"]) / float(params["density"])  # kinematic
    U = float(params["bulk_velocity"])
    nx = int(params["n_axial"])
    nr = int(params["n_radial"])

    _update_transport(case_dir, nu=nu)
    _update_u_inlet(case_dir, U=U)
    _write_block_mesh(case_dir, radius=r, length=L, n_axial=nx, n_radial=nr)

    meta["parameters"] = params
    write_meta(case_dir, meta)

    re_num = float(params["density"]) * U * (2 * r) / float(params["viscosity"])
    return {
        "parameters": params,
        "kinematic_viscosity": nu,
        "reynolds_number": re_num,
        "laminar_ok": re_num < 2300,
    }


def _update_transport(case_dir: Path, *, nu: float) -> None:
    path = case_dir / "constant" / "transportProperties"
    if not path.is_file():
        return
    text = path.read_text(encoding="utf-8")
    new_text, n = re.subn(
        r"(nu\s+\[[^\]]+\]\s+)([0-9.eE+-]+)\s*;",
        rf"\g<1>{nu:.8g};",
        text,
        count=1,
    )
    if n == 0:
        new_text, n = re.subn(
            r"(nu\s+)([0-9.eE+-]+)\s*;",
            rf"\g<1>{nu:.8g};",
            text,
            count=1,
        )
    if n:
        path.write_text(new_text, encoding="utf-8")


def _update_u_inlet(case_dir: Path, *, U: float) -> None:
    path = case_dir / "0" / "U"
    if not path.is_file():
        return
    text = path.read_text(encoding="utf-8")
    text2 = re.sub(
        r"internalField\s+uniform\s+\([^)]+\)\s*;",
        f"internalField   uniform ({U:.8g} 0 0);",
        text,
        count=1,
    )
    text2 = re.sub(
        r"(inlet\s*\{[^}]*value\s+uniform\s+)\([^)]+\)(\s*;)",
        rf"\g<1>({U:.8g} 0 0)\2",
        text2,
        count=1,
        flags=re.DOTALL,
    )
    path.write_text(text2, encoding="utf-8")


def _write_block_mesh(
    case_dir: Path,
    *,
    radius: float,
    length: float,
    n_axial: int,
    n_radial: int,
) -> None:
    """Rewrite blockMeshDict for a 2-D half-channel of height=radius, length=L."""
    path = case_dir / "system" / "blockMeshDict"
    content = f"""/*--------------------------------*- C++ -*----------------------------------*\\
FoamFile
{{
    version     2.0;
    format      ascii;
    class       dictionary;
    object      blockMeshDict;
}}
// * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * //
// Generated by vCFD set_pipe_parameters (half-channel height = radius).

scale   1;

vertices
(
    (0 0 0)
    ({length:.8g} 0 0)
    ({length:.8g} {radius:.8g} 0)
    (0 {radius:.8g} 0)
    (0 0 0.01)
    ({length:.8g} 0 0.01)
    ({length:.8g} {radius:.8g} 0.01)
    (0 {radius:.8g} 0.01)
);

blocks
(
    hex (0 1 2 3 4 5 6 7) ({n_axial} {n_radial} 1) simpleGrading (1 1 1)
);

edges
(
);

boundary
(
    inlet
    {{
        type patch;
        faces
        (
            (0 4 7 3)
        );
    }}
    outlet
    {{
        type patch;
        faces
        (
            (1 2 6 5)
        );
    }}
    walls
    {{
        type wall;
        faces
        (
            (3 7 6 2)
        );
    }}
    symmetry
    {{
        type symmetryPlane;
        faces
        (
            (0 1 5 4)
        );
    }}
    frontAndBack
    {{
        type empty;
        faces
        (
            (0 3 2 1)
            (4 5 6 7)
        );
    }}
);

mergePatchPairs
(
);

// ************************************************************************* //
"""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
